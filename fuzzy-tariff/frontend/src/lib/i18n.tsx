type LegacyDict = Record<string, string | Record<string, string>>
const LEGACY = legacy as unknown as Record<Lang, LegacyDict>

const EMOJI = /[\p{Extended_Pictographic}\u{FE0F}\u{200D}\u{20E3}]/gu

/** Strip emoji, "1." numbering, and HTML from the legacy strings. */
export function clean(s: string): string {
  return s
    .replace(/<span class="num">\d+<\/span>/g, '')
    .replace(/<[^>]+>/g, '')
    .replace(EMOJI, '')
    .replace(/^\s*■\s*/, '')
    .replace(/^\s*\d+\.\s+/, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = EXTRA[lang]?.[key] ?? EXTRA.en[key]
  if (s === undefined) {
    const v = LEGACY[lang]?.[key] ?? LEGACY.en[key]
    s = typeof v === 'string' ? clean(v) : key
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function deviceName(lang: Lang, id: string): string {
  const names = (LEGACY[lang]?.devNames ?? LEGACY.en.devNames) as Record<string, string>
  return names?.[id] ?? id
}

export const LangContext = createContext<Lang>('en')
export function useT() {
  const lang = useContext(LangContext)
  return { lang, t: (k: string, v?: Record<string, string | number>) => translate(lang, k, v) }
}
